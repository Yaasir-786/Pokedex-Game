const generateRandom = () => {
  return Math.floor(Math.random() * 250);
};

export const fetchPokemon = async () => {
  const response = await fetch(
    `https://pokeapi.co/api/v2/pokemon/${generateRandom()}`,
  );
  const data = await response.json();

  let optionOne = data.name;
  let optionTwo = pokemonNames[generateRandom()];
  let optionThree = pokemonNames[generateRandom()];
  let optionFour = pokemonNames[generateRandom()];

  optionTwo === optionOne ? pokemonNames[generateRandom()] : optionTwo;
  optionThree === optionOne ? pokemonNames[generateRandom()] : optionThree;
  optionFour === optionOne ? pokemonNames[generateRandom()] : optionFour;

  let options = [optionOne, optionTwo, optionThree, optionFour]
    .map((name) => name.toLowerCase())
    .sort();

  console.log(options);

  return {
    name: data.name,
    image: data.sprites.other.dream_world.front_default,
    options: options,
  };
};
